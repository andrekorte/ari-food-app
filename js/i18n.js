window.LANG = localStorage.getItem("arifood_lang") || "en";

window.t = function (key) {
  return (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
};

window.toggleLang = function () {
  LANG = LANG === "en" ? "th" : "en";
  localStorage.setItem("arifood_lang", LANG);
};
